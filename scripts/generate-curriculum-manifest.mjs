import { readFile, writeFile } from 'node:fs/promises';

const lessonIds = {
  l1: 'lesson-001-game-system-mental-model',
  l2: 'lesson-002-files-folders-projects',
  l3: 'lesson-003-unity-environment-setup',
  l4: 'lesson-004-create-first-project',
  l5: 'lesson-005-editor-map',
  l6: 'lesson-006-gameobject-component-transform',
};
const sources = await Promise.all([
  readFile(new URL('../src/learning/course.ts', import.meta.url), 'utf8'),
  readFile(new URL('../src/learning/foundationLessons.ts', import.meta.url), 'utf8'),
]);
const rows = [];
for (const source of sources) {
  for (const match of source.matchAll(/step\(\['(l[1-6]-[^']+)','([^']+)','[^']+',\d+,(\d+),/g)) {
    const [, stepId, kind, xpText] = match;
    const prefix = stepId.split('-')[0];
    rows.push({ stepId, lessonId: lessonIds[prefix], xp: Number(xpText), finale: kind === 'finale' });
  }
}
if (rows.length !== 84) throw new Error(`Expected 84 published steps, found ${rows.length}.`);
const entries = rows.map((row) => `  '${row.lessonId}/${row.stepId}': { xp: ${row.xp}, finale: ${row.finale} },`).join('\n');
const output = `// Generated by scripts/generate-curriculum-manifest.mjs. Do not edit by hand.\nexport const curriculum = {\n${entries}\n} as const;\n\nexport const totalPublishedSteps = ${rows.length};\n`;
await writeFile(new URL('../functions/src/curriculum.generated.ts', import.meta.url), output);
